// Builds the design tokens (src/design-system/tokens, W3C DTCG format) into
// CSS custom properties and a typed TypeScript module, after checking that
// every layer only references the layer right below it:
//
//   primitive  → raw values, no references to other layers
//   semantic   → may only reference primitive tokens
//   component  → may only reference semantic tokens
//
//   pnpm tokens

import { readdir, readFile } from 'node:fs/promises'
import { join, relative } from 'node:path'
import StyleDictionary from 'style-dictionary'
import type { Format, TransformedToken } from 'style-dictionary/types'

const root = join(import.meta.dirname, '..')
const tokensDir = join(root, 'src/design-system/tokens')
const outputDir = join(root, 'src/design-system/generated')

const layers = ['primitive', 'semantic', 'component'] as const
type Layer = (typeof layers)[number]
const allowedReferences: Record<Layer, Layer[]> = {
  primitive: ['primitive'],
  semantic: ['primitive'],
  component: ['semantic'],
}

interface FlatToken {
  path: string
  value: unknown
  file: string
}

function flatten(node: Record<string, unknown>, file: string, prefix: string[] = []): FlatToken[] {
  if ('$value' in node) return [{ path: prefix.join('.'), value: node.$value, file }]
  return Object.entries(node)
    .filter(([key, child]) => !key.startsWith('$') && typeof child === 'object' && child !== null)
    .flatMap(([key, child]) => flatten(child as Record<string, unknown>, file, [...prefix, key]))
}

function referencesIn(value: unknown): string[] {
  return [...JSON.stringify(value).matchAll(/\{([^{}]+)\}/g)].map((match) => match[1])
}

async function checkLayers(): Promise<string[]> {
  const layerOf = new Map<string, Layer>()
  const tokens: (FlatToken & { layer: Layer })[] = []
  for (const layer of layers) {
    for (const name of await readdir(join(tokensDir, layer))) {
      if (!name.endsWith('.json')) continue
      const file = join(tokensDir, layer, name)
      for (const token of flatten(JSON.parse(await readFile(file, 'utf8')), file)) {
        layerOf.set(token.path, layer)
        tokens.push({ ...token, layer })
      }
    }
  }

  const errors: string[] = []
  for (const token of tokens) {
    if (token.layer === 'primitive' && !token.path.startsWith('primitive.')) {
      errors.push(`${token.path}: primitive tokens must live under the "primitive" group`)
    }
    for (const reference of referencesIn(token.value)) {
      const target = layerOf.get(reference)
      if (!target) errors.push(`${token.path}: unknown reference {${reference}}`)
      else if (!allowedReferences[token.layer].includes(target)) {
        errors.push(
          `${token.path} (${token.layer}, ${relative(root, token.file)}) references {${reference}} (${target}); ` +
            `${token.layer} tokens may only reference ${allowedReferences[token.layer].join(', ')} tokens`,
        )
      }
    }
  }
  return errors
}

// Flat map of resolved values for code that needs tokens at runtime
// (e.g. durations for timers). Durations become numbers in milliseconds.
const typescriptFormat: Format = {
  name: 'slxd/typescript',
  format: ({ dictionary }) => {
    const entries = dictionary.allTokens
      .filter((token: TransformedToken) => token.path[0] !== 'primitive')
      .map((token: TransformedToken) => {
        const value =
          token.$type === 'duration' && typeof token.$value === 'string'
            ? Number.parseFloat(token.$value)
            : token.$value
        return `  '${token.path.join('.')}': ${JSON.stringify(value)},`
      })
    return [
      '// Generated by scripts/build-tokens.ts. Do not edit.',
      '// Semantic and component tokens with resolved values; durations in ms.',
      'export const tokens = {',
      ...entries,
      '} as const',
      '',
      'export type TokenName = keyof typeof tokens',
      '',
    ].join('\n')
  },
}

// Token families, one documentation page each. Primitive and semantic files
// are named after their family; component tokens are classified by type.
type Family = 'color' | 'typography' | 'spacing' | 'shape' | 'motion' | 'layer'

function familyOf(token: TransformedToken, layer: string, file: string): Family {
  if (layer !== 'component') return file.replace(/\.json$/, '') as Family
  const path = token.path.join('.')
  switch (token.$type) {
    case 'color':
      return 'color'
    case 'fontFamily':
    case 'fontWeight':
      return 'typography'
    case 'duration':
    case 'cubicBezier':
      return 'motion'
    case 'shadow':
      return 'shape'
    case 'number':
      return path.includes('line-height') ? 'typography' : 'layer'
    default:
      if (path.includes('font')) return 'typography'
      if (/radius|border-width|stroke-width/.test(path)) return 'shape'
      return 'spacing'
  }
}

// Every token with its layer, family, CSS variable, resolved value and the
// token it points to, for the documentation pages in Storybook.
const docsFormat: Format = {
  name: 'slxd/docs',
  format: ({ dictionary, platform }) => {
    const rows = dictionary.allTokens.map((token: TransformedToken) => {
      const [layer, file] = token.filePath.split('/tokens/')[1]?.split('/') ?? []
      const original = token.original.$value
      const reference = typeof original === 'string' && original.includes('{') ? original : null
      return {
        name: `--${platform.prefix}-${token.path.join('-')}`,
        path: token.path.join('.'),
        layer,
        family: familyOf(token, layer, file),
        type: token.$type,
        value: typeof token.$value === 'string' ? token.$value : JSON.stringify(token.$value),
        reference,
        description: token.$description ?? null,
      }
    })
    return [
      '// Generated by scripts/build-tokens.ts. Do not edit.',
      `export const tokenDocs = ${JSON.stringify(rows, null, 2)} as const`,
      '',
    ].join('\n')
  },
}

const errors = await checkLayers()
if (errors.length > 0) {
  console.error(`Token layer violations:\n${errors.map((error) => `  - ${error}`).join('\n')}`)
  process.exit(1)
}

const dictionary = new StyleDictionary({
  source: [join(tokensDir, '**/*.json')],
  log: { verbosity: 'default' },
  hooks: {
    formats: {
      [typescriptFormat.name]: typescriptFormat.format,
      [docsFormat.name]: docsFormat.format,
    },
  },
  platforms: {
    css: {
      prefix: 'slxd',
      // Values stay in stage pixels: no rem conversion.
      transforms: ['name/kebab', 'color/css', 'fontFamily/css', 'cubicBezier/css', 'shadow/css/shorthand'],
      buildPath: `${outputDir}/`,
      files: [
        {
          destination: 'tokens.css',
          format: 'css/variables',
          options: {
            // Each variable points to the layer below, so the chain is visible in devtools.
            outputReferences: true,
            fileHeader: () => ['Generated by scripts/build-tokens.ts. Do not edit.'],
          },
        },
      ],
    },
    typescript: {
      prefix: 'slxd',
      transforms: ['name/kebab', 'color/css', 'fontFamily/css', 'cubicBezier/css', 'shadow/css/shorthand'],
      buildPath: `${outputDir}/`,
      files: [
        { destination: 'tokens.ts', format: typescriptFormat.name },
        { destination: 'tokens.docs.ts', format: docsFormat.name },
      ],
    },
  },
})

await dictionary.buildAllPlatforms()
console.log('Tokens built in src/design-system/generated/')
